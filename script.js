function handlePhotoUpload(event) {
  const file = event.target.files?.[0];
  const preview = document.getElementById('photoPreview');
  if (!preview) return;
  if (!file) {
    const placeholder = document.createElement('span');
    placeholder.textContent = state.lang === 'ro'
      ? 'Încarcă sau fotografiază clientul pentru a începe'
      : 'Upload or capture a client photo to begin';
    preview.replaceChildren(placeholder);
    return;
  }
  if (!file.type.startsWith('image/')) {
    preview.replaceChildren(document.createTextNode(state.lang === 'ro' ? 'Selectează doar imagini.' : 'Please select an image file only.'));
    return;
  }
  if (file.size > 2 * 1024 * 1024) {
    preview.replaceChildren(document.createTextNode(state.lang === 'ro' ? 'Imaginea este prea mare. Folosește maxim 2 MB.' : 'The image is too large. Use a file up to 2 MB.'));
    return;
  }
  const reader = new FileReader();
  reader.onerror = () => {
    preview.replaceChildren(document.createTextNode(state.lang === 'ro' ? 'Nu s-a putut încărca imaginea.' : 'The image could not be loaded.'));
  };
  reader.onload = () => {
    const image = document.createElement('img');
    image.src = reader.result;
    image.alt = 'Client photo preview';
    image.loading = 'lazy';
    preview.replaceChildren(image);
  };
  reader.readAsDataURL(file);
}

