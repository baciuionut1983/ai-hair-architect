function escapeHtml(value = '') {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function sanitizeText(value, maxLength = 140) {
  return String(value ?? '')
    .trim()
    .replace(/[<>]/g, '')
    .slice(0, maxLength);
}

function getApiBaseUrl() {
  const hostname = window.location.hostname || '127.0.0.1';
  const isSameBackendHost = hostname === '127.0.0.1' || hostname === 'localhost';
  if (window.location.port === '3000') {
    return '';
  }
  return isSameBackendHost ? `http://${hostname}:3000` : '';
}

async function syncSubscriptionStateFromBackend() {
  const apiBase = getApiBaseUrl();
  try {
    const response = await fetch(`${apiBase}/api/subscriptions`);
    if (!response.ok) {
      return;
    }
    const subscriptions = await response.json();
    const latestEntry = Object.entries(subscriptions || {}).sort((a, b) => {
      const left = a[1]?.updatedAt || '';
      const right = b[1]?.updatedAt || '';
      return right.localeCompare(left);
    })[0];
    if (!latestEntry) {
      return;
    }
    const [, subscription] = latestEntry;
    if (subscription?.status === 'active') {
      state.billing.enabled = true;
      state.billing.pending = false;
      state.billing.plan = subscription.plan || state.billing.plan || 'pro';
      safeStorageSet('ai-hair-architect-direct-debit', JSON.stringify(state.billing));
      updateDirectDebitUI();
      updateAccessControls();
      const reminder = document.getElementById('subscriptionReminder');
      const badge = document.getElementById('subscriptionBadge');
      const countdown = document.getElementById('subscriptionCountdown');
      if (reminder) {
        reminder.textContent = state.lang === 'ro'
          ? 'Abonamentul este activ. Nu există reminderuri de expirare în acest moment.'
          : 'Your subscription is active. No expiration reminder is pending.';
        reminder.classList.remove('warning', 'expired');
      }
      if (badge) {
        badge.textContent = state.lang === 'ro' ? 'Status plan: activ' : 'Plan status: active';
        badge.classList.remove('expired');
      }
      if (countdown) {
        countdown.textContent = state.lang === 'ro' ? 'Timp rămas: 30 de zile' : 'Time remaining: 30 days';
      }
    }
  } catch (error) {
    console.warn('Unable to sync subscription state from backend:', error);
  }
}

function safeStorageGet(key) {
  try {
    return localStorage.getItem(key);
  } catch (error) {
    console.warn('Storage read failed:', error);
    return null;
  }
}

function safeStorageSet(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch (error) {
    console.warn('Storage write failed:', error);
  }
}

function safeStorageRemove(key) {
  try {
    localStorage.removeItem(key);
  } catch (error) {
    console.warn('Storage remove failed:', error);
  }
}

function readStoredJson(key, fallback) {
  try {
    const raw = safeStorageGet(key);
    return raw ? JSON.parse(raw) : fallback;
  } catch (error) {
    console.warn('Invalid stored JSON for', key, error);
    return fallback;
  }
}

function isValidEmail(value) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(value || '').trim().toLowerCase());
}

function showConfirmationModal(message, confirmAction) {
  const modal = document.getElementById('confirmModal');
  const confirmBody = document.getElementById('confirmModalBody');
  const cancelBtn = document.getElementById('confirmCancelBtn');
  const confirmBtn = document.getElementById('confirmConfirmBtn');
  if (!modal || !confirmBody || !cancelBtn || !confirmBtn) return;
  confirmationHandler = confirmAction;
  confirmBody.textContent = message;
  modal.classList.remove('hidden');
  cancelBtn.onclick = () => {
    modal.classList.add('hidden');
    confirmationHandler = null;
  };
  confirmBtn.onclick = () => {
    modal.classList.add('hidden');
    if (typeof confirmationHandler === 'function') {
      confirmationHandler();
    }
    confirmationHandler = null;
  };
}

function resetSessionTimer() {
  if (!state.auth.loggedIn) return;
  if (sessionTimer) {
    clearTimeout(sessionTimer);
  }
  sessionTimer = setTimeout(() => {
    state.auth.loggedIn = false;
    state.auth.role = 'professional';
    safeStorageRemove('ai-hair-architect-auth');
    updateAuthUI();
    const message = document.getElementById('authMessage');
    if (message) {
      message.textContent = state.lang === 'ro'
        ? 'Sesiunea a expirat din cauza inactivității. Te-ai deconectat.'
        : 'Session expired due to inactivity. You have been signed out.';
    }
  }, SESSION_TIMEOUT_MS);
}

function startSessionMonitoring() {
  const activityEvents = ['click', 'keydown', 'mousemove', 'touchstart', 'scroll'];
  activityEvents.forEach((eventName) => {
    document.addEventListener(eventName, resetSessionTimer, { passive: true });
  });
}

function openExtensionModal() {
  const modal = document.getElementById('extensionModal');
  const iframe = document.getElementById('extensionModalIframe');
  if (!modal || !iframe) return;
  iframe.src = 'extension.html';
  modal.classList.remove('hidden');
}

function closeExtensionModal() {
  const modal = document.getElementById('extensionModal');
  if (!modal) return;
  modal.classList.add('hidden');
}

