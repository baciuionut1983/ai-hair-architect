test.describe('Milestone 9 - Image Analysis E2E', () => {
  test('professional role uploads successfully', async ({ page }) => {
    await page.goto('/milestone9');
    await page.evaluate((token) => {
      localStorage.setItem('token', token);
    }, TOKENS.professional);

    const fileInput = page.locator('input[type="file"]');
    await expect(fileInput).toBeVisible();
  });

  test('salon role uploads successfully', async ({ page }) => {
    await page.goto('/milestone9');
    await page.evaluate((token) => {
      localStorage.setItem('token', token);
    }, TOKENS.salon);

    const fileInput = page.locator('input[type="file"]');
    await expect(fileInput).toBeVisible();
  });

  test('consumer role cannot upload (or returns auth error)', async ({ request }) => {
    const jpegBuffer = fs.readFileSync(getTestImagePath('test-valid.jpg'));

    const response = await request.post('/api/v1/uploads', {
      headers: {
        'Authorization': `Bearer ${TOKENS.consumer}`,
      },
      multipart: {
        clientId: 'test-client',
        files: {
          name: 'test.jpg',
          mimeType: 'image/jpeg',
          buffer: jpegBuffer,
        },
      },
    });

    expect([400, 401, 403]).toContain(response.status());
  });

  test('invalid token returns auth error', async ({ request }) => {
    const jpegBuffer = fs.readFileSync(getTestImagePath('test-valid.jpg'));

    const response = await request.post('/api/v1/uploads', {
      headers: {
        'Authorization': 'Bearer invalid-token-that-does-not-exist-in-database',
      },
      multipart: {
        clientId: 'test-client',
        files: {
          name: 'test.jpg',
          mimeType: 'image/jpeg',
          buffer: jpegBuffer,
        },
      },
    });

    expect([400, 401]).toContain(response.status());
  });

  test('no token returns 401', async ({ request }) => {
    const response = await request.post('/api/v1/uploads', {
      data: {
        clientId: 'test-client',
      },
    });

    expect(response.status()).toBe(401);
  });

  test('valid JPEG upload accepted', async ({ request }) => {
    const jpegBuffer = fs.readFileSync(getTestImagePath('test-valid.jpg'));

    const response = await request.post('/api/v1/uploads', {
      headers: {
        'Authorization': `Bearer ${TOKENS.professional}`,
      },
      multipart: {
        clientId: 'test-client-1',
        files: {
          name: 'test.jpg',
          mimeType: 'image/jpeg',
          buffer: jpegBuffer,
        },
      },
    });

    expect([200, 201, 400, 500]).toContain(response.status());
  });

  test('invalid file rejected', async ({ request }) => {
    const textBuffer = fs.readFileSync(getTestImagePath('test-invalid.txt'));

    const response = await request.post('/api/v1/uploads', {
      headers: {
        'Authorization': `Bearer ${TOKENS.professional}`,
      },
      multipart: {
        clientId: 'test-client-2',
        files: {
          name: 'test.txt',
          mimeType: 'text/plain',
          buffer: textBuffer,
        },
      },
    });

    expect([400, 401, 403]).toContain(response.status());
  });

  test('MIME spoofed file rejected', async ({ request }) => {
    const spoofedBuffer = fs.readFileSync(getTestImagePath('test-mime-spoofed.jpg'));

    const response = await request.post('/api/v1/uploads', {
      headers: {
        'Authorization': `Bearer ${TOKENS.professional}`,
      },
      multipart: {
        clientId: 'test-client-3',
        files: {
          name: 'spoofed.jpg',
          mimeType: 'image/jpeg',
          buffer: spoofedBuffer,
        },
      },
    });

    expect([400, 401, 403]).toContain(response.status());
  });
});
